/**
 * Returns the translated label for a tile, or the original English label if no
 * translation is found for the selected language.
 */
export function translateLabel(label: string, languageCode: LanguageCode): string {
  if (languageCode === 'en') return label;
  return TRANSLATIONS[languageCode]?.[label] ?? label;
}

